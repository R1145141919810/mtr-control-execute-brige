package org.mtbridge.core;

import org.mtr.core.data.Depot;
import org.mtr.core.data.Platform;
import org.mtr.core.data.Siding;
import org.mtr.core.data.Vehicle;
import org.mtr.core.simulation.Simulator;
import org.mtbridge.api.BridgeResult;

import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/**
 * The four primitive operations the bridge can perform on a running simulator.
 *
 * <p>Everything here runs on the simulator thread. The rules encoded below come from how the
 * simulator actually works, not from what would be convenient:</p>
 *
 * <ul>
 *   <li>A train's path is generated by its siding and then treated as immutable for the whole
 *       run. Changing where a running train goes is therefore <em>not</em> a field write; the
 *       path has to be regenerated, which is only possible while the siding has no active
 *       trains (regeneration drops them).</li>
 *   <li>{@code Siding.generateRoute} is incremental: the path finder runs over the following
 *       ticks, so a command that needs a new path reports {@code DEFERRED} and the intent
 *       processor waits for the sidings to settle before departing.</li>
 *   <li>Dwell is a counter compared against the stop's configured dwell time. Holding a train
 *       means preventing that counter from reaching the departure threshold.</li>
 * </ul>
 */
public final class GameActions {

	private GameActions() {
	}

	// ---------------------------------------------------------------- lookup

	/**
	 * Enumerates the vehicles of a siding.
	 *
	 * <p>The simulator keeps them in a private set that is not part of the published API, so the
	 * bridge reads it reflectively. This is the one place where reflection is unavoidable, and
	 * it is isolated here so a future API addition only has to change this method.</p>
	 */
	@SuppressWarnings("unchecked")
	public static List<Vehicle> vehicles(Siding siding) {
		if (siding == null) {
			return List.of();
		}
		try {
			final Object value = Reflect.get(siding, "vehicles");
			if (value instanceof Iterable<?> iterable) {
				final List<Vehicle> result = new ArrayList<>();
				for (final Object element : iterable) {
					if (element instanceof Vehicle vehicle) {
						result.add(vehicle);
					}
				}
				return result;
			}
		} catch (Throwable ignored) {
			// siding without a vehicle set yet
		}
		return List.of();
	}

	public static Vehicle findVehicle(Simulator simulator, String id) {
		final long numeric = parseId(id);
		if (numeric == 0L) {
			return null;
		}
		for (final Siding siding : simulator.sidingIdMap.values()) {
			for (final Vehicle vehicle : vehicles(siding)) {
				if (vehicle.getId() == numeric) {
					return vehicle;
				}
			}
		}
		return null;
	}

	public static Vehicle findByRidingEntity(Simulator simulator, UUID ridingEntity) {
		if (ridingEntity == null) {
			return null;
		}
		for (final Siding siding : simulator.sidingIdMap.values()) {
			for (final Vehicle vehicle : vehicles(siding)) {
				if (hasRider(vehicle, ridingEntity)) {
					return vehicle;
				}
			}
		}
		return null;
	}

	private static boolean hasRider(Vehicle vehicle, UUID ridingEntity) {
		final boolean[] found = {false};
		try {
			vehicle.vehicleExtraData.iterateRidingEntities(entity -> found[0] |= ridingEntity.equals(Reflect.get(entity, "uuid")));
		} catch (Throwable ignored) {
			return false;
		}
		return found[0];
	}

	public static Siding owningSiding(Simulator simulator, Vehicle vehicle) {
		for (final Siding siding : simulator.sidingIdMap.values()) {
			for (final Vehicle candidate : vehicles(siding)) {
				if (candidate == vehicle) {
					return siding;
				}
			}
		}
		return null;
	}

	public static Platform platform(Simulator simulator, String platformId) {
		final long numeric = parseId(platformId);
		return numeric == 0L ? null : simulator.platformIdMap.get(numeric);
	}

	public static int activeVehicles(Siding siding) {
		return vehicles(siding).size();
	}

	// ---------------------------------------------------------------- primitives

	/**
	 * Regenerates a siding's path so its next departure calls at {@code platform}.
	 *
	 * <p>{@code Siding.generateRoute} clears the siding's vehicle set - including {@code self},
	 * the train we are re-routing. That is how the host regenerates depot paths itself: the
	 * parked train is dropped and re-created from the siding's car set once the new path
	 * settles, usually within a second and with a new vehicle id.</p>
	 *
	 * <p>So the guard must only reject when regeneration would hurt somebody <em>else</em>:
	 * another running train (dropped mid-service) or another parked train sharing the siding
	 * (dropped and re-created without being asked). Counting every vehicle - the first live
	 * version of this check - rejected the only case the feature exists for.</p>
	 */
	public static BridgeResult regenerateTo(Simulator simulator, Siding siding, Platform platform, long now, Vehicle self) {
		if (siding == null) {
			return BridgeResult.rejected(self == null ? "" : hex(self.getId()),
				hex(platform == null ? 0 : platform.getId()), "vehicle has no siding", now);
		}
		if (platform == null) {
			return BridgeResult.rejected(self == null ? "" : hex(self.getId()), "", "unknown platform", now);
		}
		boolean otherRunning = false;
		int otherParked = 0;
		for (final Vehicle candidate : vehicles(siding)) {
			if (candidate == self) {
				continue;
			}
			if (candidate.getIsOnRoute()) {
				otherRunning = true;
			} else {
				otherParked++;
			}
		}
		if (otherRunning) {
			return BridgeResult.rejected(self == null ? "" : hex(self.getId()), hex(platform.getId()),
				"another train in siding " + siding.getName() + " is running; regeneration would drop it", now);
		}
		if (otherParked > 0) {
			return BridgeResult.rejected(self == null ? "" : hex(self.getId()), hex(platform.getId()),
				otherParked + " other parked train(s) share siding " + siding.getName() + "; regeneration would drop them", now);
		}
		return startRouteGeneration(simulator, siding, platform, self, now);
	}

	/** Route generation strategies, tried in order until the siding actually has an outbound path. */
	public static final int ROUTE_STRATEGIES = 3;

	public static String strategyName(int strategy) {
		return switch (strategy) {
			case 0 -> "generateRoute(platform, null, -1)";
			case 1 -> "generateRoute(platform, platform, 0)";
			case 2 -> "Depot.generateDepots([depot])";
			default -> "unknown";
		};
	}

	/**
	 * Launches one strategy. Success here only means "the attempt was accepted" - whether a path
	 * materialises is checked by the caller on later ticks via {@link #routeSegments(Siding)}.
	 */
	public static BridgeResult startRouteGeneration(Simulator simulator, Siding siding, Platform platform,
													Vehicle self, long now) {
		final String train = self == null ? "" : hex(self.getId());
		final String target = platform == null ? "" : hex(platform.getId());
		if (platform == null) {
			return BridgeResult.rejected(train, "", "unknown platform", now);
		}
		if (siding == null) {
			return BridgeResult.rejected(train, target, "vehicle has no siding", now);
		}
		try {
			siding.generateRoute(platform, null, -1, cruisingAltitude(siding));
			return BridgeResult.deferred(train, target,
				"route strategy 0 started: " + strategyName(0), now, now + 2000);
		} catch (Throwable throwable) {
			return BridgeResult.failed(train, target, "generateRoute failed: " + throwable.getMessage(), now);
		}
	}

	/** Executes a later strategy after the previous one failed to produce a path. */
	public static BridgeResult nextRouteStrategy(Simulator simulator, Siding siding, Platform platform, int strategy, long now) {
		final String target = platform == null ? "" : hex(platform.getId());
		try {
			if (strategy == 1) {
				siding.generateRoute(platform, platform, 0, cruisingAltitude(siding));
			} else if (strategy == 2) {
				regenerateDepot(simulator, siding);
			} else {
				return BridgeResult.failed("", target, "no further route strategy", now);
			}
			return BridgeResult.deferred("", target, "route strategy " + strategy + " started: " + strategyName(strategy), now, now + 2000);
		} catch (Throwable throwable) {
			return BridgeResult.failed("", target, "route strategy " + strategy + " failed: " + throwable.getMessage(), now);
		}
	}

	/** Depot level regeneration: the host's own entry point, and the only one that rebuilds timetables. */
	public static void regenerateDepot(Simulator simulator, Siding siding) throws Exception {
		if (siding.area == null) {
			throw new IllegalStateException("siding has no depot");
		}
		final Class<?> listClass = Class.forName("org.mtr.libraries.it.unimi.dsi.fastutil.objects.ObjectArrayList");
		final Object list = listClass.getConstructor().newInstance();
		listClass.getMethod("add", Object.class).invoke(list, siding.area);
		Depot.class.getMethod("generateDepots", Simulator.class, listClass).invoke(null, simulator, list);
	}

	/** Snapshot of a siding's generated paths, used to roll back a failed regeneration. */
	public record PathSnapshot(java.util.List<Object> sidingToMain, java.util.List<Object> mainRoute,
							   java.util.List<Object> mainToSiding) {
		public boolean empty() {
			return sidingToMain.isEmpty() && mainRoute.isEmpty() && mainToSiding.isEmpty();
		}
	}

	/**
	 * Captures the siding's current paths.
	 *
	 * <p>{@code generateRoute} clears first and builds later; when the build fails the siding is
	 * left with nothing - and the host does not rebuild it on restart, so a single probe can
	 * permanently strand a depot road. Taking a snapshot before every attempt lets the bridge put
	 * the previous path back when no strategy produced a new one.</p>
	 */
	public static PathSnapshot snapshotPaths(Siding siding) {
		return new PathSnapshot(copyPath(siding, "pathSidingToMainRoute"),
			copyPath(siding, "pathMainRoute"), copyPath(siding, "pathMainRouteToSiding"));
	}

	private static java.util.List<Object> copyPath(Siding siding, String field) {
		final java.util.List<Object> copy = new ArrayList<>();
		try {
			final Object list = Reflect.get(siding, field);
			final Object sizeValue = Reflect.callAny(list, "size");
			final int size = sizeValue instanceof Number number ? number.intValue() : 0;
			for (int index = 0; index < size; index++) {
				copy.add(Reflect.callAny(list, "get", index));
			}
		} catch (Throwable ignored) {
			// field missing or empty
		}
		return copy;
	}

	/** Restores a snapshot. Returns false when the host list could not be written back. */
	public static boolean restorePaths(Siding siding, PathSnapshot snapshot) {
		if (snapshot == null || siding == null) {
			return false;
		}
		try {
			writePath(siding, "pathSidingToMainRoute", snapshot.sidingToMain());
			writePath(siding, "pathMainRoute", snapshot.mainRoute());
			writePath(siding, "pathMainRouteToSiding", snapshot.mainToSiding());
			return true;
		} catch (Throwable ignored) {
			return false;
		}
	}

	private static void writePath(Siding siding, String field, java.util.List<Object> values) throws Exception {
		final Object list = Reflect.get(siding, field);
		Reflect.callAny(list, "clear");
		for (final Object value : values) {
			Reflect.callAny(list, "add", value);
		}
	}

	/**
	 * Bests the host's own path cache to disk so a regenerated route survives a restart.
	 *
	 * <p>Live testing showed a successful regeneration followed by a save can come back empty
	 * after restart, because the path only lived in memory. Called only when the path is
	 * non-empty, so an in-progress regeneration can never persist an empty path.</p>
	 */
	public static boolean persistPath(Siding siding) {
		if (siding == null || routeSegments(siding) <= 0) {
			return false;
		}
		try {
			Reflect.callAny(siding, "writePathCache");
		} catch (Throwable ignored) {
			return false;
		}
		// Read back: "the reflection call returned" is not the same as "the path survived".
		// Live testing showed ok=true while the host still ignored the cache after restart, so
		// persisting is only reported as true when the in-memory path is still intact.
		return routeSegments(siding) > 0;
	}

	/** Depot level regeneration with a readable outcome instead of a thrown exception. */
	public static boolean regenerateDepotQuietly(Simulator simulator, Siding siding) {
		try {
			regenerateDepot(simulator, siding);
			return true;
		} catch (Throwable ignored) {
			return false;
		}
	}

	/** Number of path segments currently generated for this siding; 0 means "no outbound path". */
	public static int routeSegments(Siding siding) {
		if (siding == null) {
			return 0;
		}
		try {
			final Object path = Reflect.get(siding, "pathSidingToMainRoute");
			final Object size = Reflect.callAny(path, "size");
			return size instanceof Number number ? number.intValue() : 0;
		} catch (Throwable ignored) {
			return 0;
		}
	}

	/** First vehicle currently parked or running at a siding, used to re-acquire a re-created train. */
	public static Vehicle firstVehicle(Siding siding) {
		final List<Vehicle> all = vehicles(siding);
		return all.isEmpty() ? null : all.get(0);
	}

	/**
	 * Makes a parked train leave.
	 *
	 * <p>The first version fabricated {@code departureIndex = 0} and called {@code startUp}. That
	 * looked like it worked (no exception) but the host's own dispatch loop then saw an index
	 * outside the departure timetable and dropped the vehicle - the train was re-created and sat
	 * in the depot forever. A departure index is only meaningful if the siding actually has a
	 * slot for it, so:</p>
	 *
	 * <ol>
	 *   <li>a valid scheduled index is used as-is (early departure of a scheduled train);</li>
	 *   <li>otherwise the siding is asked for a slot via {@code addDeparture(now)} and the host
	 *       dispatches it on the next tick - we never invent an index;</li>
	 *   <li>if the siding refuses (manual sidings), the command fails with a readable reason
	 *       instead of silently parking the train.</li>
	 * </ol>
	 */
	public static BridgeResult depart(Simulator simulator, Vehicle vehicle, Siding siding, long now) {
		if (vehicle.getIsOnRoute()) {
			return BridgeResult.rejected(hex(vehicle.getId()), "", "train is already running", now);
		}
		try {
			final long departureIndex = Reflect.getLong(vehicle, "departureIndex");
			if (departureIndex >= 0) {
				Reflect.setLong(vehicle, "sidingDepartureTime", now);
				vehicle.startUp(departureIndex, now);
				return BridgeResult.applied(hex(vehicle.getId()), "", "train departed on its scheduled slot " + departureIndex, now);
			}
			if (siding == null) {
				return BridgeResult.failed(hex(vehicle.getId()), "", "train has no siding to request a departure from", now);
			}
			// The timetable may have been cleared by the path regeneration; rebuild it for this
			// depot first, which is the host's own entry point for exactly that.
			// Ask the siding for a slot, then read the real index back from the timetable.
			// "added == true" alone is not enough: the host only starts trains whose
			// departureIndex points at an existing slot, so we take the index we just created.
			final int before = departures(siding).size();
			boolean added = siding.addDeparture(now);
			if (!added && siding.area != null) {
				try {
					siding.area.generatePlatformDirectionsAndWriteDeparturesToSidings();
					added = siding.addDeparture(now);
				} catch (Throwable ignored) {
					// fall through to the failure below
				}
			}
			final List<Long> timetable = departures(siding);
			int index = -1;
			if (added && timetable.size() > before) {
				index = timetable.size() - 1;
			} else if (added && !timetable.isEmpty()) {
				index = timetable.size() - 1;
			}
			if (index >= 0) {
				final long departureTime = timetable.get(index);
				Reflect.setLong(vehicle, "departureIndex", index);
				Reflect.setLong(vehicle, "sidingDepartureTime", departureTime);
				vehicle.startUp(index, departureTime);
				return BridgeResult.applied(hex(vehicle.getId()), "",
					"departed on timetable slot " + index + " (t+0, timetable=" + timetable.size() + ")", now);
			}
			if (siding.getIsManual()) {
				return BridgeResult.rejected(hex(vehicle.getId()), "",
					"siding " + siding.getName() + " is manual; take the controls or schedule a departure", now);
			}
			return BridgeResult.failed(hex(vehicle.getId()), "",
				"no departure slot available (addDeparture=" + added + ", timetable=" + timetable.size() + ")", now);
		} catch (Throwable throwable) {
			return BridgeResult.failed(hex(vehicle.getId()), "", "departure failed: " + throwable.getMessage(), now);
		}
	}

	/** Reads a siding's departure timetable (private in the host, read-only here). */
	public static List<Long> departures(Siding siding) {
		final List<Long> result = new ArrayList<>();
		if (siding == null) {
			return result;
		}
		try {
			final Object list = Reflect.get(siding, "departures");
			final Object sizeValue = Reflect.callAny(list, "size");
			final int size = sizeValue instanceof Number number ? number.intValue() : 0;
			for (int index = 0; index < size; index++) {
				final Object value = Reflect.callAny(list, "getLong", index);
				result.add(value instanceof Number number ? number.longValue() : 0L);
			}
		} catch (Throwable ignored) {
			// no timetable yet
		}
		return result;
	}

	/**
	 * Stops a parked train from being dispatched again. Only valid once the train is back at a
	 * siding: clearing the departure index while it is running makes the simulator drop it.
	 */
	public static BridgeResult parkAndHold(Vehicle vehicle, long now) {
		if (vehicle.getIsOnRoute()) {
			return BridgeResult.rejected(hex(vehicle.getId()), "", "train is still running; it must finish its run first", now);
		}
		try {
			Reflect.setLong(vehicle, "departureIndex", -1L);
			Reflect.setLong(vehicle, "sidingDepartureTime", -1L);
			return BridgeResult.applied(hex(vehicle.getId()), "", "train parked and removed from the departure plan", now);
		} catch (Throwable throwable) {
			return BridgeResult.failed(hex(vehicle.getId()), "", "parking failed: " + throwable.getMessage(), now);
		}
	}

	/** Prevents a stopped train's dwell counter from reaching the departure threshold. */
	public static void holdDwell(Vehicle vehicle) {
		if (isStopped(vehicle)) {
			Reflect.setNumber(vehicle, "elapsedDwellTime", 0.0);
		}
	}

	public static boolean isStopped(Vehicle vehicle) {
		return speed(vehicle) <= 0.001;
	}

	public static double speed(Vehicle vehicle) {
		try {
			return Reflect.getDouble(vehicle, "speed");
		} catch (Throwable ignored) {
			return 0.0;
		}
	}

	public static double railProgress(Vehicle vehicle) {
		try {
			return Reflect.getDouble(vehicle, "railProgress");
		} catch (Throwable ignored) {
			return 0.0;
		}
	}

	public static long dwellElapsed(Vehicle vehicle) {
		try {
			return (long) Reflect.getNumber(vehicle, "elapsedDwellTime");
		} catch (Throwable ignored) {
			return 0L;
		}
	}

	private static long cruisingAltitude(Siding siding) {
		try {
			final Depot depot = siding.area;
			return depot == null ? 0L : depot.getCruisingAltitude();
		} catch (Throwable ignored) {
			return 0L;
		}
	}

	public static long parseId(String id) {
		if (id == null || id.isBlank()) {
			return 0L;
		}
		final String trimmed = id.trim();
		try {
			return Long.parseLong(trimmed);
		} catch (NumberFormatException ignored) {
			try {
				return Long.parseUnsignedLong(trimmed.startsWith("0x") ? trimmed.substring(2) : trimmed, 16);
			} catch (NumberFormatException exception) {
				return 0L;
			}
		}
	}

	public static String hex(long id) {
		return String.format("%016x", id);
	}
}
